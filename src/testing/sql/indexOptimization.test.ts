import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

/**
 * Executes the dev_staging index-cleanup migration against a real Postgres
 * (PGlite, WASM) seeded with the pre-migration dev_staging index set, and
 * asserts the resulting index contract rather than reading the SQL as text.
 *
 * What must hold before the coordinator applies it to live dev_staging:
 * - the three FK-support / composite indexes exist with their exact columns;
 * - the two `views` indexes and the PK-duplicate site_settings index are gone;
 * - primary keys, project_requests_active_idx and skills_categories_position_idx
 *   are untouched;
 * - the `public` schema receives nothing;
 * - replaying the whole file changes nothing (safe resume after a partial
 *   apply or a retried run).
 */

const migrationPath = fileURLToPath(
  new URL(
    '../../../supabase/migrations/20261017134507_optimize_indexes_dev_staging.sql',
    import.meta.url
  )
);

let db: PGlite;

async function indexNames(): Promise<string[]> {
  const result = await db.query<{ indexname: string }>(
    `select indexname from pg_indexes
      where schemaname = 'dev_staging'
      order by indexname`
  );
  return result.rows.map((row) => row.indexname);
}

async function indexDef(name: string): Promise<string | null> {
  const result = await db.query<{ indexdef: string }>(
    `select indexdef from pg_indexes
      where schemaname = 'dev_staging' and indexname = $1`,
    [name]
  );
  return result.rows[0]?.indexdef ?? null;
}

/**
 * Index definition with identifier quoting removed, so assertions are not
 * brittle about keywords the deparser quotes (e.g. `position` -> `"position"`).
 */
async function indexDefNoQuotes(name: string): Promise<string> {
  return (await indexDef(name))?.replace(/"/g, '') ?? '';
}

/** Column names of an index, in index key order (not the catalog order). */
async function indexColumns(name: string): Promise<string[]> {
  const result = await db.query<{ attname: string }>(
    `select a.attname
       from pg_index i
       cross join lateral unnest(i.indkey::smallint[])
         with ordinality as k(attnum, ord)
       join pg_attribute a
         on a.attrelid = i.indrelid and a.attnum = k.attnum
      where i.indexrelid = to_regclass('dev_staging.' || $1)
      order by k.ord`,
    [name]
  );
  return result.rows.map((row) => row.attname);
}

beforeAll(async () => {
  db = new PGlite();
  // Pre-migration dev_staging shape: the redundant indexes exist and the
  // FK-support indexes do not.
  await db.exec(`
    create schema dev_staging;

    create table dev_staging.blog_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      views integer not null default 0
    );
    create index blog_posts_views_idx on dev_staging.blog_posts (views);

    create table dev_staging.portfolio_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      views integer not null default 0
    );
    create index portfolio_posts_views_idx on dev_staging.portfolio_posts (views);

    create table dev_staging.skills_categories (
      id bigint primary key generated by default as identity,
      position integer not null default 0
    );
    create index skills_categories_position_idx
      on dev_staging.skills_categories (position);

    create table dev_staging.skills (
      id bigint primary key generated by default as identity,
      category_id bigint references dev_staging.skills_categories (id)
        on delete cascade,
      position integer
    );

    create table dev_staging.site_settings (
      id bigint primary key generated by default as identity
    );
    create index site_settings_single_row_idx on dev_staging.site_settings (id);

    create table dev_staging.project_requests (
      id bigint primary key generated by default as identity,
      archived boolean not null default false,
      created_at timestamptz not null default now()
    );
    create index project_requests_active_idx
      on dev_staging.project_requests (archived, created_at desc);
  `);
  const sql = await readFile(migrationPath, 'utf8');
  await db.exec(sql);
  // Replay proves idempotency: a retried or resumed apply is a no-op.
  await db.exec(sql);
}, 60_000);

afterAll(async () => db.close());

describe('dev_staging index optimization', () => {
  it('creates the FK-support indexes with their exact columns', async () => {
    expect(await indexNames()).toEqual(
      expect.arrayContaining([
        'blog_posts_author_id_idx',
        'portfolio_posts_author_id_idx',
        'skills_category_position_id_idx',
      ])
    );
    expect(await indexColumns('blog_posts_author_id_idx')).toEqual([
      'author_id',
    ]);
    expect(await indexColumns('portfolio_posts_author_id_idx')).toEqual([
      'author_id',
    ]);
  });

  it('builds one skills composite index beginning (category_id, position, id)', async () => {
    expect(await indexColumns('skills_category_position_id_idx')).toEqual([
      'category_id',
      'position',
      'id',
    ]);
    expect(await indexDefNoQuotes('skills_category_position_id_idx')).toContain(
      '(category_id, position, id)'
    );
    // The leading category_id column covers the FK, so no standalone
    // category_id index is created.
    expect(await indexNames()).not.toContain('skills_category_id_idx');
  });

  it('drops the redundant views and PK-duplicate indexes', async () => {
    const names = await indexNames();
    for (const gone of [
      'blog_posts_views_idx',
      'portfolio_posts_views_idx',
      'site_settings_single_row_idx',
    ]) {
      expect(names).not.toContain(gone);
    }
  });

  it('leaves primary keys and the in-use indexes untouched', async () => {
    expect(await indexNames()).toEqual(
      expect.arrayContaining([
        'blog_posts_pkey',
        'portfolio_posts_pkey',
        'skills_pkey',
        'skills_categories_pkey',
        'site_settings_pkey',
        'project_requests_pkey',
        'project_requests_active_idx',
        'skills_categories_position_idx',
      ])
    );
    expect(await indexDefNoQuotes('project_requests_active_idx')).toContain(
      '(archived, created_at DESC)'
    );
    expect(await indexDefNoQuotes('skills_categories_position_idx')).toContain(
      '(position)'
    );
  });

  it('never creates anything in the public schema', async () => {
    const publicRelations = await db.query<{ count: number }>(
      `select count(*)::int as count
         from pg_class c
         join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'public' and c.relkind in ('r', 'i', 'S')`
    );
    expect(publicRelations.rows[0]?.count).toBe(0);
  });
});
