import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

/**
 * Executes the dev post-visibility migration against a real Postgres (PGlite,
 * WASM) seeded with the exact pre-migration dev RLS shape, and proves:
 *
 * - anon/authenticated see only `hidden = false` posts on BOTH tables;
 * - a future unhidden post stays readable (no publish-date predicate);
 * - author-profile visibility inherits that boundary through the Phase 1C
 *   policy, which reads the dev post tables.
 *
 * The author policy is NOT recreated by this migration; it is seeded here as the
 * Phase 1C definition so the inheritance can be observed.
 */

const migrationPath = fileURLToPath(
  new URL(
    '../../../supabase/migrations/20261017165547_harden_post_reads_dev_staging.sql',
    import.meta.url
  )
);

const A = '11111111-1111-1111-1111-111111111111'; // only a visible post
const B = '22222222-2222-2222-2222-222222222222'; // only a hidden post
const C = '33333333-3333-3333-3333-333333333333'; // only a future unhidden post
const D = '44444444-4444-4444-4444-444444444444'; // no posts

let db: PGlite;

let anonBlogBefore: number[] = [];
let anonBlogAfter: number[] = [];
let anonPortfolioAfter: number[] = [];
let authBlogAfter: number[] = [];
let authPortfolioAfter: number[] = [];
let anonProfilesBefore: string[] = [];
let anonProfilesAfter: string[] = [];
let publicBefore: string[] = [];
let publicAfter: string[] = [];
let aclBefore: (string | null)[] = [];
let aclAfter: (string | null)[] = [];

async function visibleIds(
  role: 'anon' | 'authenticated',
  table: string
): Promise<number[]> {
  await db.exec(`set role ${role}`);
  try {
    const res = await db.query<{ id: number }>(
      `select id from dev_staging.${table} order by id`
    );
    return res.rows.map((row) => row.id);
  } finally {
    await db.exec('reset role');
  }
}

async function anonVisibleProfiles(): Promise<string[]> {
  await db.exec('set role anon');
  try {
    const res = await db.query<{ id: string }>(
      `select id from dev_staging.user_profiles order by id`
    );
    return res.rows.map((row) => row.id);
  } finally {
    await db.exec('reset role');
  }
}

async function publicObjects(): Promise<string[]> {
  const res = await db.query<{ relname: string }>(
    `select c.relname
       from pg_class c join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind in ('r', 'i', 'S')
      order by c.relname`
  );
  return res.rows.map((row) => row.relname);
}

async function tableAcl(table: string): Promise<string | null> {
  const res = await db.query<{ acl: string | null }>(
    `select relacl::text as acl from pg_class where oid = to_regclass($1)`,
    [table]
  );
  return res.rows[0]?.acl ?? null;
}

beforeAll(async () => {
  db = new PGlite();
  await db.exec(`
    create role anon;
    create role authenticated;
    create schema dev_staging;

    create table dev_staging.blog_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      hidden boolean not null default false,
      created_at timestamptz not null default now()
    );
    create table dev_staging.portfolio_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      hidden boolean not null default false,
      created_at timestamptz not null default now()
    );
    create table dev_staging.user_profiles (
      id uuid primary key,
      display_name text
    );

    alter table dev_staging.blog_posts enable row level security;
    alter table dev_staging.portfolio_posts enable row level security;
    alter table dev_staging.user_profiles enable row level security;

    grant usage on schema dev_staging to anon, authenticated;
    grant select on dev_staging.blog_posts, dev_staging.portfolio_posts
      to anon, authenticated;
    grant select on dev_staging.user_profiles to anon, authenticated;

    -- PRE-migration permissive read policies (the state being hardened).
    create policy "Allow public read access to blog_posts"
      on dev_staging.blog_posts for select to anon, authenticated using (true);
    create policy "Public can read posts"
      on dev_staging.portfolio_posts for select to anon, authenticated using (true);

    -- Unrelated policy that must survive unchanged.
    create policy "Admins and mods can insert"
      on dev_staging.blog_posts for insert to authenticated
      with check (author_id is not null);

    -- Phase 1C author policy, bound to the DEV post tables (not recreated here).
    create policy user_profiles_public_author_read
      on dev_staging.user_profiles for select to anon
      using (
        (exists (select 1 from dev_staging.blog_posts bp
                  where bp.author_id = user_profiles.id))
        or (exists (select 1 from dev_staging.portfolio_posts pp
                     where pp.author_id = user_profiles.id))
      );

    insert into dev_staging.user_profiles (id, display_name) values
      ('${A}', 'author-a'), ('${B}', 'author-b'),
      ('${C}', 'author-c'), ('${D}', 'author-d');

    -- blog_posts: visible past / hidden past / future unhidden
    insert into dev_staging.blog_posts (author_id, hidden, created_at) values
      ('${A}', false, now() - interval '1 day'),
      ('${B}', true,  now() - interval '1 day'),
      ('${C}', false, now() + interval '1 day');
    insert into dev_staging.portfolio_posts (author_id, hidden, created_at) values
      ('${A}', false, now() - interval '1 day'),
      ('${B}', true,  now() - interval '1 day'),
      ('${C}', false, now() + interval '1 day');
  `);

  anonBlogBefore = await visibleIds('anon', 'blog_posts');
  anonProfilesBefore = await anonVisibleProfiles();
  publicBefore = await publicObjects();
  aclBefore = [
    await tableAcl('dev_staging.blog_posts'),
    await tableAcl('dev_staging.portfolio_posts'),
    await tableAcl('dev_staging.user_profiles'),
  ];

  const sql = await readFile(migrationPath, 'utf8');
  await db.exec(sql);
  // Replay proves idempotency: a retried or resumed apply is a no-op.
  await db.exec(sql);

  anonBlogAfter = await visibleIds('anon', 'blog_posts');
  anonPortfolioAfter = await visibleIds('anon', 'portfolio_posts');
  authBlogAfter = await visibleIds('authenticated', 'blog_posts');
  authPortfolioAfter = await visibleIds('authenticated', 'portfolio_posts');
  anonProfilesAfter = await anonVisibleProfiles();
  publicAfter = await publicObjects();
  aclAfter = [
    await tableAcl('dev_staging.blog_posts'),
    await tableAcl('dev_staging.portfolio_posts'),
    await tableAcl('dev_staging.user_profiles'),
  ];
}, 120_000);

afterAll(async () => db.close());

describe('dev post visibility hardening', () => {
  it('replays safely and replaces the permissive policies', async () => {
    const pols = await db.query<{ tablename: string; policyname: string }>(
      `select tablename, policyname from pg_policies
        where schemaname = 'dev_staging'
          and tablename in ('blog_posts', 'portfolio_posts')
        order by tablename, policyname`
    );
    const names = pols.rows.map((r) => `${r.tablename}.${r.policyname}`);
    expect(names).toContain('blog_posts.cms_published_read');
    expect(names).toContain('portfolio_posts.cms_published_read');
    expect(names).not.toContain('blog_posts.Allow public read access to blog_posts');
    expect(names).not.toContain('portfolio_posts.Public can read posts');
    // no duplicate policy names anywhere
    expect(names.length).toBe(new Set(names).size);
  }, 30_000);

  it('hides drafts from anon and authenticated on both tables', () => {
    // pre-migration the permissive USING(true) exposed the hidden row
    expect(anonBlogBefore).toEqual([1, 2, 3]);
    expect(anonBlogAfter).toEqual([1, 3]);
    expect(anonPortfolioAfter).toEqual([1, 3]);
    expect(authBlogAfter).toEqual([1, 3]);
    expect(authPortfolioAfter).toEqual([1, 3]);
  });

  it('keeps a future unhidden post readable (no publish-date predicate)', () => {
    expect(anonBlogAfter).toContain(3);
    expect(anonPortfolioAfter).toContain(3);
    expect(authBlogAfter).toContain(3);
    expect(authPortfolioAfter).toContain(3);
  });

  it('behaves identically on blog_posts and portfolio_posts', () => {
    expect(anonBlogAfter).toEqual(anonPortfolioAfter);
    expect(authBlogAfter).toEqual(authPortfolioAfter);
  });

  it('author visibility inherits the post boundary', () => {
    // pre-migration the hidden-only author was exposed
    expect(anonProfilesBefore).toEqual([A, B, C]);
    // A (visible post) and C (future unhidden post) remain; B (hidden only)
    // and D (no posts) are no longer visible.
    expect(anonProfilesAfter).toEqual([A, C]);
    expect(anonProfilesAfter).not.toContain(B);
    expect(anonProfilesAfter).not.toContain(D);
  });

  it('keeps the blog INSERT policy unchanged', async () => {
    const res = await db.query<{ cmd: string; qual: string | null }>(
      `select p.polcmd::text as cmd, pg_get_expr(polwithcheck, p.polrelid) as qual
         from pg_policy p join pg_class c on c.oid = p.polrelid
        where c.relname = 'blog_posts' and p.polname = 'Admins and mods can insert'`
    );
    expect(res.rows).toHaveLength(1);
    expect(res.rows[0]?.cmd).toBe('a');
    expect(res.rows[0]?.qual).toContain('author_id');
  }, 30_000);

  it('modifies no public object and changes no grant', () => {
    expect(publicAfter).toEqual(publicBefore);
    expect(publicAfter).toEqual([]);
    expect(aclAfter).toEqual(aclBefore);
  });

  it('contains only the expected policy DROP/CREATE operations', async () => {
    const raw = await readFile(migrationPath, 'utf8');
    const stripped = raw
      .split('\n')
      .map((line) => line.replace(/--.*$/, ''))
      .join('\n');
    const statements = stripped
      .split(';')
      .map((part) => part.replace(/\s+/g, ' ').trim().toLowerCase())
      .filter(Boolean);
    expect(statements).toEqual([
      'drop policy if exists "allow public read access to blog_posts" on dev_staging.blog_posts',
      'drop policy if exists cms_published_read on dev_staging.blog_posts',
      'create policy cms_published_read on dev_staging.blog_posts for select to anon, authenticated using (hidden = false)',
      'drop policy if exists "public can read posts" on dev_staging.portfolio_posts',
      'drop policy if exists cms_published_read on dev_staging.portfolio_posts',
      'create policy cms_published_read on dev_staging.portfolio_posts for select to anon, authenticated using (hidden = false)',
    ]);
    const sql = stripped.toLowerCase();
    expect(sql).not.toMatch(/\bpublic\./);
    expect(sql).not.toMatch(
      /\b(alter|grant|revoke|insert|update|delete|truncate|create index|drop index)\b/
    );
  });
});
