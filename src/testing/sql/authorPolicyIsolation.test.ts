import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

/**
 * Executes the dev author-policy isolation migration against a real Postgres
 * (PGlite, WASM) and proves the policy's relation bindings switch from
 * production to the dev clone.
 *
 * Relation identity is asserted from the CATALOG (pg_depend holds the OIDs the
 * policy expression bound at CREATE time) — not from SQL text — so the test
 * cannot pass merely because a schema name appears in a deparsed string.
 *
 * A behavioural proof backs it: three authors are seeded so that the two
 * candidate relations yield DIFFERENT visible sets. Before the migration anon
 * sees the authors with production posts; after it, the authors with dev posts.
 */

const migrationPath = fileURLToPath(
  new URL(
    '../../../supabase/migrations/20261017160247_isolate_dev_author_profile_policy.sql',
    import.meta.url
  )
);

const POLICY = 'user_profiles_public_author_read';
const DEV_ONLY = '11111111-1111-1111-1111-111111111111';
const PROD_ONLY = '22222222-2222-2222-2222-222222222222';
const BOTH = '33333333-3333-3333-3333-333333333333';

let db: PGlite;

type PolicySnapshot = {
  policyname: string;
  cmd: string;
  roles: string | null;
  qual: string | null;
  with_check: string | null;
};

let bindingsBefore: string[] = [];
let visibleBefore: string[] = [];
let policiesBefore: PolicySnapshot[] = [];
let publicBefore: string[] = [];
let bindingsAfter: string[] = [];
let visibleAfter: string[] = [];
let policiesAfter: PolicySnapshot[] = [];
let publicAfter: string[] = [];

/** Schema-qualified relations the author policy actually binds (pg_depend OIDs). */
async function authorPolicyBindings(): Promise<string[]> {
  const res = await db.query<{ ref_schema: string; ref_relation: string }>(
    `select distinct rn.nspname as ref_schema, rc.relname as ref_relation
       from pg_depend d
       join pg_policy p on d.objid = p.oid and d.classid = 'pg_policy'::regclass
       join pg_class c on c.oid = p.polrelid
       join pg_namespace n on n.oid = c.relnamespace
       join pg_class rc on rc.oid = d.refobjid and d.refclassid = 'pg_class'::regclass
       join pg_namespace rn on rn.oid = rc.relnamespace
      where n.nspname = 'dev_staging' and c.relname = 'user_profiles'
        and p.polname = $1
        and rc.oid <> c.oid
      order by 1, 2`,
    [POLICY]
  );
  return res.rows.map((row) => `${row.ref_schema}.${row.ref_relation}`);
}

/** Profile ids an unprivileged `anon` caller can actually read. */
async function anonVisibleProfileIds(): Promise<string[]> {
  await db.exec('set role anon');
  try {
    const res = await db.query<{ id: string }>(
      `select id from dev_staging.user_profiles order by id`
    );
    return res.rows.map((row) => row.id);
  } finally {
    await db.exec('reset role');
  }
}

async function devPolicySnapshot(): Promise<PolicySnapshot[]> {
  const res = await db.query<PolicySnapshot>(
    `select policyname, cmd, roles::text as roles, qual, with_check
       from pg_policies
      where schemaname = 'dev_staging'
      order by policyname`
  );
  return res.rows;
}

async function publicRelationSnapshot(): Promise<string[]> {
  const res = await db.query<{ relname: string }>(
    `select c.relname
       from pg_class c
       join pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relkind in ('r', 'i', 'S')
      order by c.relname`
  );
  return res.rows.map((row) => row.relname);
}

beforeAll(async () => {
  db = new PGlite();
  await db.exec(`
    create role anon;
    create role authenticated;
    create schema auth;
    create schema dev_staging;
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('test.uid', true), '')::uuid $$;

    -- Production-clone stand-ins (relations the leaky policy reads).
    create table public.blog_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      hidden boolean not null default false
    );
    create table public.portfolio_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      hidden boolean not null default false
    );

    -- Dev clone.
    create table dev_staging.blog_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      hidden boolean not null default false
    );
    create table dev_staging.portfolio_posts (
      id bigint primary key generated by default as identity,
      author_id uuid,
      hidden boolean not null default false
    );
    create table dev_staging.user_profiles (
      id uuid primary key,
      display_name text
    );

    alter table dev_staging.user_profiles enable row level security;
    alter table dev_staging.blog_posts enable row level security;

    grant usage on schema dev_staging to anon;
    grant usage on schema public to anon;
    grant select on dev_staging.user_profiles to anon;
    grant select on dev_staging.blog_posts, dev_staging.portfolio_posts to anon;
    grant select on public.blog_posts, public.portfolio_posts to anon;

    -- Unrelated dev policies that the migration must not touch.
    create policy cms_published_read
      on dev_staging.blog_posts for select to anon using (true);
    create policy user_profiles_authenticated_read
      on dev_staging.user_profiles for select to authenticated using (true);
    create policy user_profiles_self_update
      on dev_staging.user_profiles for update to authenticated
      using (id = (select auth.uid()))
      with check (id = (select auth.uid()));

    -- PRE-migration author policy: bound to PRODUCTION relations (the leak).
    create policy user_profiles_public_author_read
      on dev_staging.user_profiles for select to anon
      using (
        (exists (select 1 from public.blog_posts bp where bp.author_id = user_profiles.id))
        or (exists (select 1 from public.portfolio_posts pp where pp.author_id = user_profiles.id))
      );

    -- Seed three authors whose dev/production authorship diverges.
    insert into dev_staging.user_profiles (id, display_name) values
      ('${DEV_ONLY}', 'dev-only'),
      ('${PROD_ONLY}', 'prod-only'),
      ('${BOTH}', 'both');
    insert into dev_staging.blog_posts (author_id) values
      ('${DEV_ONLY}'), ('${BOTH}');
    insert into public.blog_posts (author_id) values
      ('${PROD_ONLY}'), ('${BOTH}');
  `);

  bindingsBefore = await authorPolicyBindings();
  visibleBefore = await anonVisibleProfileIds();
  policiesBefore = await devPolicySnapshot();
  publicBefore = await publicRelationSnapshot();

  const sql = await readFile(migrationPath, 'utf8');
  await db.exec(sql);
  // Replay proves idempotency: a retried or resumed apply is a no-op.
  await db.exec(sql);

  bindingsAfter = await authorPolicyBindings();
  visibleAfter = await anonVisibleProfileIds();
  policiesAfter = await devPolicySnapshot();
  publicAfter = await publicRelationSnapshot();
}, 120_000);

afterAll(async () => db.close());

describe('dev author profile policy isolation', () => {
  it('starts leaked: the policy binds production relations', () => {
    expect(bindingsBefore).toEqual([
      'public.blog_posts',
      'public.portfolio_posts',
    ]);
    expect(visibleBefore).toEqual([PROD_ONLY, BOTH].sort());
  });

  it('replays safely and keeps the policy present', () => {
    expect(bindingsAfter.length).toBeGreaterThan(0);
    const names = policiesAfter.map((p) => p.policyname);
    expect(names.filter((n) => n === POLICY)).toHaveLength(1);
  });

  it('binds only the dev clone post relations after the migration', () => {
    expect(bindingsAfter).toEqual([
      'dev_staging.blog_posts',
      'dev_staging.portfolio_posts',
    ]);
  });

  it('no longer depends on production post relations', () => {
    expect(bindingsAfter).not.toContain('public.blog_posts');
    expect(bindingsAfter).not.toContain('public.portfolio_posts');
    expect(bindingsAfter.some((r) => r.startsWith('public.'))).toBe(false);
  });

  it('keeps SELECT command, anon role, permissive semantics and both EXISTS branches', async () => {
    const after = policiesAfter.find((p) => p.policyname === POLICY);
    expect(after?.cmd).toBe('SELECT');
    expect((after?.roles ?? '').replace(/^\{|\}$/g, '')).toBe('anon');
    const qual = (after?.qual ?? '').toUpperCase();
    expect(qual.match(/EXISTS/g)?.length).toBe(2);
    expect(qual).toContain(' OR ');
    expect(qual).toContain('AUTHOR_ID');
  }, 30_000);

  it('introduces no hidden filter', async () => {
    const before = policiesBefore.find((p) => p.policyname === POLICY);
    const after = policiesAfter.find((p) => p.policyname === POLICY);
    expect((before?.qual ?? '').toLowerCase()).not.toContain('hidden');
    expect((after?.qual ?? '').toLowerCase()).not.toContain('hidden');
    expect((after?.qual ?? '').toLowerCase()).not.toContain('created_at');
  });

  it('changes which authors anon can read, per the dev relations (behavioural proof)', () => {
    // Pre-fix: the production-authored profile was exposed. Post-fix: only the
    // dev-authored set is, which is the environment-isolation guarantee.
    expect(visibleBefore).toEqual([PROD_ONLY, BOTH].sort());
    expect(visibleAfter).toEqual([DEV_ONLY, BOTH].sort());
    expect(visibleAfter).not.toContain(PROD_ONLY);
  });

  it('changes no other dev_staging policy', () => {
    const before = new Map(policiesBefore.map((p) => [p.policyname, p]));
    const after = new Map(policiesAfter.map((p) => [p.policyname, p]));
    expect([...after.keys()].sort()).toEqual([...before.keys()].sort());
    for (const [name, beforePolicy] of before) {
      const afterPolicy = after.get(name);
      expect(afterPolicy).toBeDefined();
      expect([name, afterPolicy?.cmd, afterPolicy?.roles]).toEqual([
        name,
        beforePolicy.cmd,
        beforePolicy.roles,
      ]);
      expect(afterPolicy?.with_check).toBe(beforePolicy.with_check);
      if (name !== POLICY) {
        expect([name, afterPolicy?.qual]).toEqual([name, beforePolicy.qual]);
      }
    }
    expect(
      after.get(POLICY)?.qual === before.get(POLICY)?.qual
    ).toBe(false);
  });

  it('alters no object in the production/public schema', () => {
    expect(publicAfter).toEqual(publicBefore);
    expect(publicAfter).toContain('blog_posts');
    expect(publicAfter).toContain('portfolio_posts');
  });
});
